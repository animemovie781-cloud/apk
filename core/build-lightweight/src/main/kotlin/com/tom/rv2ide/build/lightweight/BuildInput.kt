package com.tom.rv2ide.build.lightweight

import java.io.File
import com.tom.rv2ide.projects.IProjectManager

/**
 * Contains all the parameters and configuration required for a build.
 */
data class BuildInput(
    val project: IProjectManager,
    val isDebug: Boolean,
    val buildLogger: BuildLogger,
    val cancellationToken: BuildCancellationToken
) {
    val projectDir: File = project.getProjectDirectory()
    
    // Derived properties that could be configurable later
    val buildDir: File = File(projectDir, "build")
    val intermediatesDir: File = File(buildDir, "intermediates")
    val generatedDir: File = File(buildDir, "generated")
    val resourcesDir: File = File(buildDir, "resources")
    val classesDir: File = File(buildDir, "classes")
    val dexDir: File = File(buildDir, "dex")
    val apkDir: File = File(buildDir, "apk")
    val cacheDir: File = File(buildDir, "cache")
    val tempDir: File = File(buildDir, "temp")
    
    // APK output paths
    val debugApkPath: File = File(File(apkDir, "debug"), "app-debug.apk")
    val releaseApkPath: File = File(File(apkDir, "release"), "app-release.apk")
    
    val outputApk: File = if (isDebug) debugApkPath else releaseApkPath

    /**
     * Prepares the build directories, ensuring they exist and are empty if necessary.
     */
    fun prepareDirectories() {
        // We only clear the outputs that are directly generated by the current build.
        // Incremental cache should be preserved if we implement it.
        // For now, doing a clean build setup.
        
        // Clean directories except cache
        arrayOf(intermediatesDir, generatedDir, resourcesDir, classesDir, dexDir, tempDir).forEach { dir ->
            if (dir.exists()) {
                dir.deleteRecursively()
            }
            dir.mkdirs()
        }
        
        outputApk.parentFile?.mkdirs()
    }
}
